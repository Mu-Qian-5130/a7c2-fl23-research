"""Fixed CP layout selected for code/state growth and at most18 look slots."""
REGION_START = 0x02700000
REGION_END = 0x02B00000
CODE_START = REGION_START
CODE_BYTES = 0x00180000
STATE_START = CODE_START + CODE_BYTES
STATE_BYTES = 0x00200000
DATA_START = STATE_START + STATE_BYTES
DATA_BYTES = 0x00080000
MAX_LOOK_SLOTS = 18
ROOT_VA = 0x01209B40
assert DATA_START + DATA_BYTES == REGION_END
assert CODE_BYTES + STATE_BYTES == 0x00380000
