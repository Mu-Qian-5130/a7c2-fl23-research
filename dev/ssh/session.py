"""Prepare/start/inspect/stop an explicit RAM-only ILCE-7CM2 SSH experiment.

Preparation is offline. Device commands create a new journal, open one service
session, and never retry a native request after an unknown outcome. No startup
edits, remounts, original SSH configuration or firmware/settings writes.
"""
import argparse
import base64
from hashlib import sha256
import ipaddress
import json
from pathlib import Path
import re
import shutil
import struct
import subprocess
import sys
import time
import uuid

ROOT=Path(__file__).resolve().parents[2]
sys.path[:0]=[str(ROOT/'src'),str(ROOT/'src/looks')]
from desktopapp.paths import write_json

REQUEST=struct.Struct('<8sIIQII')
REPORT=struct.Struct('<8sIIqqQ')
FILES=('dropbear','hostkey','authorized_keys','session.sh')
PROC_PATHS=('/proc/sys/kernel/random/boot_id','/proc/version','/proc/self/mounts','/proc/net/dev','/proc/net/route','/proc/net/fib_trie','/proc/net/tcp')


def ipv4(value):
    address=ipaddress.IPv4Address(value)
    if address.is_unspecified or address.is_multicast or address.is_loopback:
        raise ValueError('Select the camera Wi-Fi IPv4 address')
    return str(address)


def public_key(raw):
    """One explicit Ed25519 client public key, with no embedded options/commands."""
    parts=raw.decode('ascii').strip().split()
    if len(parts)<2 or parts[0]!='ssh-ed25519':raise ValueError('Select an Ed25519 public key (.pub), never a private key')
    try:
        value=base64.b64decode(parts[1],validate=True)
    except ValueError as exc:raise ValueError('Invalid SSH public key') from exc
    if len(value)!=51 or value[:19]!=b'\0\0\0\x0bssh-ed25519\0\0\0\x20':raise ValueError('Invalid Ed25519 key encoding')
    return (parts[0]+' '+parts[1]+'\n').encode('ascii')


def executable(path):
    from elftools.elf.elffile import ELFFile
    path=Path(path)
    if not 0<path.stat().st_size<=4*1024*1024:raise ValueError('Dropbear size outside supported range')
    with path.open('rb') as stream:
        elf=ELFFile(stream)
        if elf['e_machine']!='EM_AARCH64' or elf['e_type']!='ET_EXEC':raise ValueError('Use a static AArch64 executable')
        for segment in elf.iter_segments():
            if segment['p_type'] in ('PT_INTERP','PT_DYNAMIC'):raise ValueError('Dynamic SSH binary is not supported')


def prepare(artifacts,hostkey,client_key,bind,output,*,zig=None,listen_all=False):
    """No key generation on the camera; all inputs are prepared on the host."""
    from looktool.nativebuild import compile_worker
    camera_ip=ipv4(bind);bind='0.0.0.0' if listen_all else camera_ip;artifacts=Path(artifacts)
    executable(artifacts/'dropbear')
    if hostkey is None:
        from Cryptodome.PublicKey import ECC
        generated=ECC.generate(curve='Ed25519')
        key=b'\0\0\0\x0bssh-ed25519\0\0\0\x40'+generated.seed+generated.public_key().export_key(format='raw')
    else:key=Path(hostkey).read_bytes()
    # Dropbear's Ed25519 private-key format: string('ssh-ed25519'), string(64 bytes).
    if len(key)!=83 or key[:19]!=b'\0\0\0\x0bssh-ed25519\0\0\0\x40':
        raise ValueError('Use an Ed25519 host key generated by this build of dropbearkey')
    client=public_key(Path(client_key).read_bytes())
    output=Path(output).resolve();output.mkdir(parents=True,exist_ok=False)
    session_id=uuid.uuid4().hex[:16];session='/tmp_wbshd/a7c2-ssh-'+session_id
    payloads={'dropbear':(artifacts/'dropbear').read_bytes(),'hostkey':key,
              'authorized_keys':client,'session.sh':(Path(__file__).parent/'session.sh').read_bytes()}
    rows=[];definitions=[]
    for index,name in enumerate(FILES):
        raw=payloads[name];mode=0o700 if name in ('dropbear','session.sh') else 0o600
        (output/name).write_bytes(raw)
        (output/name).chmod(mode)
        digest=sha256(raw).hexdigest();rows.append(dict(name=name,bytes=len(raw),sha256=digest,mode=mode))
        definitions.append('static const u8 hash_%d[]={%s};'%(index,','.join(str(b) for b in bytes.fromhex(digest))))
    quote=lambda value:json.dumps(value)
    definitions+=['static const char session_path[]='+quote(session)+';',
        'static const char session_name[]='+quote(session.split('/')[-1])+';',
        'static const char server_path[]='+quote(session+'/dropbear')+';',
        'static const char script_path[]='+quote(session+'/session.sh')+';',
        'static const char bind_ip[]='+quote(bind)+';',
        'static const u32 file_count=4;',
        'static const struct File files[]={'+','.join('{'+quote(r['name'])+','+str(r['bytes'])+'UL,hash_'+str(i)+','+str(r['mode'])+'}' for i,r in enumerate(rows))+'};']
    header=output/'ssh.private.h';header.write_text('\n'.join(definitions)+'\n',encoding='ascii')
    build=compile_worker(Path(__file__).parent/'temporary.c',header,output/'temporary.so',zig)
    build.pop('manifest_sha256',None)
    state=dict(schema='a7c2-temporary-ssh/1',phase='PREPARED',session_path=session,
        bind_ip=bind,camera_ip=camera_ip,port=2222,files=rows,worker=build,camera_io=False,
        firmware_written=False,settings_written=False,persistent_startup=False,
        physical_boot_verified=False,ssh_login_verified=False)
    write_json(output/'session.private.json',state)
    for name in ('dropbear-LICENSE.txt','build-info.txt','localoptions.h'):
        shutil.copy2(artifacts/name,output/name)
    return state


def load(folder):
    folder=Path(folder).resolve();state=json.loads((folder/'session.private.json').read_text(encoding='utf-8'))
    if state.get('schema')!='a7c2-temporary-ssh/1':raise ValueError('Unsupported SSH experiment')
    if not re.fullmatch(r'/tmp_wbshd/a7c2-ssh-[a-f0-9]{16}',state['session_path']):raise ValueError('Invalid session path')
    ipv4(state['camera_ip'])
    if state['bind_ip']!='0.0.0.0':ipv4(state['bind_ip'])
    if [row['name'] for row in state['files']]!=list(FILES):raise ValueError('Unexpected file list')
    wanted={'dropbear':0o700,'hostkey':0o600,'authorized_keys':0o600,'session.sh':0o700}
    for row in state['files']:
        raw=(folder/row['name']).read_bytes()
        if row['mode']!=wanted[row['name']]:raise ValueError('Unexpected session file permissions')
        if len(raw)!=row['bytes'] or sha256(raw).hexdigest()!=row['sha256']:raise ValueError('Prepared SSH file changed: '+row['name'])
    raw=(folder/'temporary.so').read_bytes()
    if len(raw)!=state['worker']['bytes'] or sha256(raw).hexdigest()!=state['worker']['sha256']:raise ValueError('Prepared SSH worker changed')
    return folder,state


def parse(raw,mode):
    if len(raw)<REPORT.size or mode!=6 and len(raw)!=REPORT.size:raise ValueError('Incomplete SSH worker result; do not replay')
    magic,version,actual,status,pid,progress=REPORT.unpack(raw[:REPORT.size])
    if (magic,version,actual)!=(b'A7SSR001',1,mode):raise ValueError('SSH worker ABI differs')
    if status:raise ValueError('SSH operation stopped: status=%d pid=%d; preserve this transaction'%(status,pid))
    report=dict(pid=pid,progress_bytes=progress)
    if mode==6:
        if len(raw)<REPORT.size+28:raise ValueError('Incomplete proc snapshot')
        lengths=struct.unpack_from('<7I',raw,REPORT.size)
        if sum(lengths)!=progress or len(raw)!=REPORT.size+28+progress or any(n>=limit for n,limit in zip(lengths,(64,1024,8192,2048,4096,32768,16384))):raise ValueError('Proc snapshot lengths differ')
        at=REPORT.size+28;report['snapshots']={}
        for path,size in zip(PROC_PATHS,lengths):
            report['snapshots'][path]=raw[at:at+size].decode('ascii');at+=size
    return report


def listening(raw,bind):
    expected=ipaddress.IPv4Address(bind).packed[::-1].hex().upper()+':08AE'
    return any(len(parts:=line.split())>3 and parts[1]==expected and parts[3]=='0A'
               for line in raw.decode('ascii').splitlines()[1:])


def run_device(folder,action,*,camera_factory=None):
    from looktool.devicesession import Camera,invoke
    from looktool import checkpoint
    from looktool.devicelock import DeviceLock
    folder,state=load(folder)
    with DeviceLock(folder/'host.lock'):
        if action=='start' and state['phase']!='PREPARED':raise ValueError('This session has already been attempted; never replay it')
        if action not in ('start','status','stop'):raise ValueError('Unknown SSH action')
        job=folder/('operation-'+action+'-'+uuid.uuid4().hex[:8]);job.mkdir()
        journal=[]
        def record(event,**values):
            journal.append(dict(event=event,**values));write_json(job/'journal.private.json',journal)
        def call(camera,mode,index=0,offset=0,count=0):
            return invoke(camera,(folder/'temporary.so').read_bytes(),stage='lut-runtime-staged.so',
                request='a7c2.install.request',result='a7c2.runtime.result',
                contents=REQUEST.pack(b'A7SSH001',mode,index,offset,count,0),mode=mode,
                decode=lambda raw:parse(raw,mode),record=record,
                save_raw=lambda raw:(job/('result-%04d.bin'%len(journal))).write_bytes(raw))
        if action=='start':
            state.update(phase='START_ATTEMPTED',operation=str(job));write_json(folder/'session.private.json',state)
        try:
            with (camera_factory or Camera)(state.get('identity')) as camera:
                if camera.identity_pending:raise ValueError('Native model identity must already be established')
                if state.get('identity'):checkpoint.same_body(state['identity'],camera.identity)
                else:state['identity']=dict(camera.identity)
                programs={name:camera.read(path) for name,path in checkpoint.PROGRAM_PATHS.items()}
                camera.byte_checks=True
                camera.pin_programs(programs['appFw.so'],programs['cpapp-b.bin'])
                if action=='start':
                    snapshot=call(camera,6)['snapshots']
                    state['source_boot_id']=snapshot['/proc/sys/kernel/random/boot_id'].strip()
                    if not re.fullmatch(r'[a-f0-9-]{36}',state['source_boot_id']):raise ValueError('Missing boot identity')
                    mount=snapshot['/proc/self/mounts'].encode();(job/'mounts-before.txt').write_bytes(mount)
                    state['devpts_mounted']=any(len(parts:=line.split())>2 and parts[1]==b'/dev/pts' and parts[2]==b'devpts' for line in mount.splitlines())
                    fib=snapshot['/proc/net/fib_trie']
                    if state['bind_ip']!='0.0.0.0' and not re.search(r'\b'+re.escape(state['bind_ip'])+r'\s*\n\s*/32 host LOCAL',fib):
                        raise ValueError('Selected Wi-Fi IP is not assigned to the camera; no SSH files uploaded')
                    tcp=snapshot['/proc/net/tcp'].encode();(job/'tcp-before.txt').write_bytes(tcp)
                    if listening(tcp,state['bind_ip']) or listening(tcp,'0.0.0.0'):raise ValueError('Port 2222 is already occupied')
                    call(camera,0)
                    for index,row in enumerate(state['files']):
                        raw=(folder/row['name']).read_bytes();offset=0
                        for at in range(0,len(raw),65536):
                            chunk=raw[at:at+65536]
                            if camera.temp_read('resource.chunk',True) is not None:raise ValueError('Existing resource chunk; preserve prior operation')
                            camera.temp_write('resource.chunk',chunk)
                            if camera.temp_read('resource.chunk')!=chunk:raise ValueError('Chunk staging differs')
                            result=call(camera,1,index,offset,len(chunk))
                            if result['progress_bytes']!=offset+len(chunk):raise ValueError('SSH chunk progress differs')
                            camera.temp_remove('resource.chunk');offset+=len(chunk)
                        if camera.read(state['session_path']+'/'+row['name'])!=raw:raise ValueError('Full SSH payload readback differs')
                    call(camera,2);result=call(camera,3);state['launch_pid']=result['pid']
                    state['phase']='LAUNCHED_UNVERIFIED'
                    write_json(folder/'session.private.json',state)
                    # Read-only observation only; never issue another launch.
                    for attempt in range(10):
                        time.sleep(.2)
                        if camera.read(state['session_path']+'/dropbear.pid',True) is None:continue
                        result=call(camera,4)
                        tcp=call(camera,6)['snapshots']['/proc/net/tcp'].encode()
                        if listening(tcp,state['bind_ip']):
                            state.update(phase='LISTENING',pid=result['pid']);break
                    if state['phase']!='LISTENING':raise ValueError('SSH launch did not establish a verified listener; preserve logs, do not replay')
                else:
                    result=call(camera,4 if action=='status' else 5)
                    state['phase']='PROCESS_RUNNING' if action=='status' else 'STOP_REQUESTED'
                    if action=='status' and listening(call(camera,6)['snapshots']['/proc/net/tcp'].encode(),state['bind_ip']):state['phase']='LISTENING'
                    if action=='stop':
                        for attempt in range(10):
                            time.sleep(.2)
                            if not listening(call(camera,6)['snapshots']['/proc/net/tcp'].encode(),state['bind_ip']):
                                state['phase']='STOPPED';break
                (job/'session.log').write_bytes(camera.read(state['session_path']+'/session.log',True) or b'')
                # Program file equality is checked independently of listener readiness.
                for name,path in checkpoint.PROGRAM_PATHS.items():
                    if camera.read(path)!=programs[name]:raise ValueError('Program files changed during SSH experiment')
                state.update(camera_io=True,operation=str(job))
                write_json(folder/'session.private.json',state)
        except BaseException as exc:
            state.update(phase='NEEDS_REVIEW',error=str(exc),operation=str(job))
            write_json(folder/'session.private.json',state);raise
    return state


def verify_login(folder,client_private):
    """Pin the independently generated host key and compare the USB boot identity."""
    folder,state=load(folder)
    if state['phase'] not in ('LISTENING','SSH_VERIFIED'):raise ValueError('First establish the temporary listener')
    host_blob=b'\0\0\0\x0bssh-ed25519\0\0\0\x20'+(folder/'hostkey').read_bytes()[-32:]
    known=folder/'known_hosts'
    target=state.get('camera_ip',state['bind_ip'])
    known.write_text('[%s]:2222 ssh-ed25519 %s\n'%(target,base64.b64encode(host_blob).decode()),encoding='ascii')
    ssh=shutil.which('ssh')
    if not ssh:raise ValueError('OpenSSH client is required on the computer')
    command=[ssh,'-F','NUL' if sys.platform=='win32' else '/dev/null','-o','BatchMode=yes',
        '-o','IdentitiesOnly=yes','-o','StrictHostKeyChecking=yes','-o','ConnectTimeout=10',
        '-o','UserKnownHostsFile='+str(known),'-p','2222','-i',str(Path(client_private).resolve()),
        'root@'+target,
        "printf 'A7C2_SSH_OK\\n' && /bin/busybox uname -m && /bin/busybox grep '^Uid:' /proc/self/status && /bin/busybox cat /proc/sys/kernel/random/boot_id"]
    done=subprocess.run(command,capture_output=True,text=True,timeout=20)
    (folder/'ssh-verify.private.log').write_text(done.stdout+'\n'+done.stderr,encoding='utf-8')
    lines=done.stdout.splitlines()
    if (done.returncode or len(lines)!=4 or lines[:2]!=['A7C2_SSH_OK','aarch64'] or
            not re.fullmatch(r'Uid:\s+0\s+0\s+0\s+0\s*',lines[2]) or lines[3]!=state['source_boot_id']):
        raise ValueError('SSH login/boot identity was not verified; inspect ssh-verify.private.log')
    state.update(phase='SSH_VERIFIED',ssh_login_verified=True)
    write_json(folder/'session.private.json',state);return state


def persistence_readiness(folder):
    """Stage two consumes physical evidence; it never edits an init file here."""
    folder,state=load(folder)
    required=('usb_exit_keeps_ssh','viewfinder','photo','playback','standby_wake','stop_verified')
    receipt_path=folder/'physical-acceptance.private.json'
    receipt=json.loads(receipt_path.read_text(encoding='utf-8')) if receipt_path.exists() else {}
    missing=[name for name in required if receipt.get(name) is not True]
    if not state.get('ssh_login_verified'):missing.insert(0,'physical SSH login with pinned host key')
    if not state.get('source_boot_id') or receipt.get('source_boot_id')!=state.get('source_boot_id'):missing.append('acceptance tied to this boot')
    if state.get('phase')!='STOPPED' and 'stop_verified' not in missing:missing.append('stop_verified')
    report=dict(schema='a7c2-ssh-persistence-readiness/1',camera_io=False,
        ready_for_startup_design=not missing,missing_physical_evidence=missing,
        startup_implemented=False,firmware_written=False,
        design=['explicit enable and disable; default off',
            'independent files and configuration; preserve original SSH manager',
            'bounded background startup; absent/corrupt payload must not block boot',
            'cold-boot, WBI/standby and exact uninstall validation'])
    write_json(folder/'persistence-readiness.private.json',report);return report


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    commands=parser.add_subparsers(dest='command',required=True)
    prepare_parser=commands.add_parser('prepare')
    for name in ('artifacts','client-key','bind-ip','output'):prepare_parser.add_argument('--'+name,required=True)
    prepare_parser.add_argument('--hostkey')
    prepare_parser.add_argument('--listen-all',action='store_true',help='Listen on 0.0.0.0 so Wi-Fi may come up after USB exits; --bind-ip is the expected camera IP for SSH verification')
    prepare_parser.add_argument('--zig')
    verify_parser=commands.add_parser('verify-login');verify_parser.add_argument('folder')
    verify_parser.add_argument('--client-private',required=True)
    persistent=commands.add_parser('persistence-readiness');persistent.add_argument('folder')
    for command in ('start','status','stop'):
        child=commands.add_parser(command);child.add_argument('folder')
        child.add_argument('--firmware',required=True,choices=['2.01'])
    args=parser.parse_args()
    if args.command=='prepare':result=prepare(args.artifacts,args.hostkey,args.client_key,args.bind_ip,args.output,zig=args.zig,listen_all=args.listen_all)
    elif args.command=='verify-login':result=verify_login(args.folder,args.client_private)
    elif args.command=='persistence-readiness':result=persistence_readiness(args.folder)
    else:result=run_device(args.folder,args.command)
    print(json.dumps(result,ensure_ascii=False,indent=2))


if __name__=='__main__':main()
